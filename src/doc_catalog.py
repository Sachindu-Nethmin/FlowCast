FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)
# Innermost first: an OS picker can sit inside the Visual Designer tab.
TABS_RE = re.compile(r"<Tabs\b[^>]*>((?:(?!<Tabs\b).)*?)</Tabs>", re.S)
TABITEM_RE = re.compile(r"<TabItem\b([^>]*)>(.*?)</TabItem>", re.S)
FENCE_RE = re.compile(r"^(\s*)```(\w*)[^\n]*\n(.*?)^\s*```\s*$", re.S | re.M)
ADMONITION_RE = re.compile(r"^:::(\w+)[^\n]*\n(.*?)^:::\s*$", re.S | re.M)
JSX_BLOCK_RE = re.compile(r"<([A-Z]\w*)\b[^>]*?/>|<([A-Z]\w*)\b.*?</\2>", re.S)
HEADING_RE = re.compile(r"^(#{1,4})\s+(.+?)\s*#*\s*$")
STEP_HEADING_RE = re.compile(r"^Step\s+(\d+)\s*[:.\-–—]?\s*(.*)$", re.I)
NUMBERED_RE = re.compile(r"^( {0,3})(\d+)[.)]\s+(.*\S)\s*$")
SUB_BULLET_RE = re.compile(r"^\s{2,}[-*+]\s+(.*\S)\s*$")
