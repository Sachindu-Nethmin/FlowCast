# ── source checkout ──────────────────────────────────────────────────────────

def sync_source(dest: Path = SOURCE_DIR) -> Path:
    """Fetch (or update) the docs Markdown only.

    The repo is mostly images; a blobless, sparse checkout of `*.md` brings
    the clone from minutes to seconds.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not (dest / ".git").exists():
        subprocess.run(["git", "clone", "--depth", "1", "--filter=blob:none",
                        "--no-checkout", DOCS_REPO, str(dest)], check=True)
        subprocess.run(["git", "-C", str(dest), "sparse-checkout", "set", "--no-cone",
                        "/en/docs/**/*.md", "/en/docs/**/*.mdx"], check=True)
        subprocess.run(["git", "-C", str(dest), "checkout", "main"], check=True)
    else:
        subprocess.run(["git", "-C", str(dest), "pull", "--depth", "1", "--quiet"],
                       check=True)
    return dest / "en" / "docs"


def source_commit(dest: Path = SOURCE_DIR) -> str:
    r = subprocess.run(["git", "-C", str(dest), "log", "-1", "--format=%h %cs"],
                       capture_output=True, text=True)
    return r.stdout.strip()


