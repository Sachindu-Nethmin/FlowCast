def _frontmatter(raw: str) -> tuple[dict, str]:
    m = FRONTMATTER_RE.match(raw)
    if not m:
        return {}, raw
    fm = {}
    for ln in m.group(1).splitlines():
        k, sep, v = ln.partition(":")
        if sep and not ln.startswith(" "):
            fm[k.strip()] = v.strip().strip('"').strip("'")
    return fm, raw[m.end():]


def _pick_tab(block: str) -> str:
    """Keep the Visual Designer tab — the one FlowCast can click through.

    Pages offer the same build as UI steps and as Ballerina code; the code tab
    is useless to a screen recorder. Failing a UI tab, take the default one.
    """
    items = TABITEM_RE.findall(block)
    if not items:
        return block
    for attrs, body in items:
        if re.search(r'value="(?:ui|unix|mac|macos)"|label="[^"]*(visual|designer|low-code|'
                     r'\bui\b|macos)', attrs, re.I):
            return body
    for attrs, body in items:
        if "default" in attrs:
            return body
    return items[0][1]


FENCE_MARK = "\u27e6FENCE:{}\u27e7"
FENCE_MARK_RE = re.compile(r"\u27e6FENCE:(\d+)\u27e7")
SHELL_LANGS = ("bash", "sh", "shell", "zsh", "console")


def _clean(body: str) -> tuple[str, list[tuple[str, str]], list[str], str]:
    """Return (procedure text, code fences, admonition texts, prerequisites).

    Each code fence leaves a marker in the text so the instruction it belongs
    to ("Run the modify command in your terminal:") can find it again.
    """
    while TABS_RE.search(body):
        body = TABS_RE.sub(lambda m: _pick_tab(m.group(1)), body)
    body = re.sub(r"^import .*$", "", body, flags=re.M)
    fences: list[tuple[str, str]] = []

    def _mark(m: re.Match) -> str:
        fences.append((m.group(2).lower(), m.group(3)))
        return f"{m.group(1)}{FENCE_MARK.format(len(fences) - 1)}"
    body = FENCE_RE.sub(_mark, body)
    admonitions, prereq = [], []
    for m in ADMONITION_RE.finditer(body):
        head = body[m.start():body.index("\n", m.start())]
        (prereq if re.search(r"prerequisite|before you begin", head, re.I)
         else admonitions).append(m.group(2))
    body = ADMONITION_RE.sub("", body)
    for m in re.finditer(r"^#{2,3}\s+(?:Prerequisites?|Before you begin|Requirements)\s*\n"
                         r"(.*?)(?=^#{1,3}\s|\Z)", body, re.S | re.M | re.I):
        prereq.append(m.group(1))
    body = JSX_BLOCK_RE.sub("", body)
    body = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", body)           # images
    # `<username>@<companyID>` is a placeholder, not markup: keep it readable.
    body = re.sub(r"`[^`\n]*`", lambda m: m.group(0).replace("<", "‹").replace(">", "›"), body)
    body = re.sub(r"<[^>\n]+>", "", body)                      # stray html
    return body, fences, admonitions, "\n".join(prereq)


# Prerequisite bullets that only ask for WSO2 Integrator itself.
OWN_ENVIRONMENT = re.compile(
    r"WSO2 Integrator|cloud setup|local setup|cloud editor|VS ?Code|Visual Studio Code|"
    r"working .*environment|Ballerina|basic (?:knowledge|understanding|familiarity)|"
    r"familiar(?:ity)? with|completed? the|understanding of", re.I)


def _requirements(prereq: str, fences: list[tuple[str, str]]) -> tuple[list[str], list[str]]:
    """(what a page needs that FlowCast cannot set up, commands it can run to
    set the rest up itself).

    Every prerequisite bullet counts except the ones asking for WSO2 Integrator
    itself — and except a bullet that carries its own one-line local command
    ("A file at the listener path. Create one: touch /tmp/x"), which FlowCast
    runs before step 1 instead.
    """
    out: list[str] = []
    setup: list[str] = []
    bullets: list[list[str]] = []
    for ln in prereq.splitlines():
        if re.match(r"^\s*[-*]\s+\S", ln):
            bullets.append([ln])
        elif bullets:
            bullets[-1].append(ln)
    for chunk in bullets:
        first = re.sub(r"^\s*[-*]\s+", "", chunk[0])
        item = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", first)
        item = FENCE_MARK_RE.sub("", re.sub(r"[*`]", "", item)).strip(" :")
        if not item or OWN_ENVIRONMENT.search(item) or len(item) <= 3:
            continue
        cmds = [c for c in (_shell_command(fences[int(m.group(1))])
                            for m in FENCE_MARK_RE.finditer("\n".join(chunk))) if c]
        if cmds:
            setup.append(cmds[0])
        else:
            out.append(item[:140])
    if not out and not setup and not bullets:
        # Prose prerequisites ("CDC must be enabled on the SQL Server database")
        prose = re.sub(r"\s+", " ", FENCE_MARK_RE.sub("", prereq)).strip()
        if prose and not OWN_ENVIRONMENT.search(prose):
            out.append(prose[:140])
    return out, setup


def _sections(body: str) -> list[tuple[int, str, list[str]]]:
    out: list[tuple[int, str, list[str]]] = [(1, "", [])]
    for ln in body.splitlines():
        m = HEADING_RE.match(ln)
        if m:
            out.append((len(m.group(1)), m.group(2).strip(), []))
        else:
            out[-1][2].append(ln)
    return out


def _items(lines: list[str]) -> list[str]:
    """Numbered instructions, each with its indented sub-bullets folded in as
    separate entries (they are usually 'set field X to Y' details)."""
    items: list[str] = []
    for ln in lines:
        m = NUMBERED_RE.match(ln)
        if m:
            items.append(m.group(3))
            continue
        if items and FENCE_MARK_RE.search(ln):
            items[-1] += " " + FENCE_MARK_RE.search(ln).group(0)
            continue
        m = SUB_BULLET_RE.match(ln)
        if m and items:
            items.append("  - " + m.group(1))
            continue
        if items and ln.startswith("   ") and ln.strip() and not ln.strip().startswith("|"):
            # wrapped continuation of the previous numbered line
            if not items[-1].startswith("  - "):
                items[-1] += " " + ln.strip()
    return items


def _paragraph_items(lines: list[str]) -> list[str]:
    """A Step section written as prose ('Click **Save Connection**. The node
    appears.') — keep the imperative sentences."""
    text = " ".join(ln.strip() for ln in lines if ln.strip() and not ln.strip().startswith("|"))
    sentences = re.split(r"(?<=[.!])\s+(?=[A-Z*])", text)
    return [s for s in sentences if IMPERATIVE.match(s)]


# ── one instruction → parser-legal lines ─────────────────────────────────────

CLICK_VERBS = re.compile(r"^(?P<pre>(?:in|on|from) the [^,]+,\s*)?(?:click|choose|pick|tap)\s+(?:on\s+)?", re.I)
ENTER_IN_RE = re.compile(
    r"^(?:enter|type|input)\s+`([^`]+)`\s+(?:in|into|as|for)\s+(?:the\s+)?\*\*([^*]+)\*\*(?:\s+(?:field|box|input))?\.?$", re.I)
SEARCH_TYPE_RE = re.compile(
    r"^(?:in the [^,]*search[^,]*,\s*)?(?:type|enter|search for|search)\s+`([^`]+)`(?:\s+in the search[\w ]*)?\.?$", re.I)
COMPOUND_SET_RE = re.compile(r"\s+and\s+(?=\*\*[^*]+\*\*\s+to\s+`)", re.I)
FIELD_VALUE_RE = re.compile(r"^\*\*([^*]+)\*\*\s*[:—–-]\s*`([^`]+)`\.?$")


# One-line commands FlowCast may run itself through the parser's shell action
# ("Run the shell command `X`"). Anything that installs, deploys, needs a
# placeholder filled in or reaches beyond this machine stays a blocker.
LOCAL_COMMAND = re.compile(r"^(echo|printf|touch|cat|cp|mv|mkdir|ls|curl)\b")
UNSAFE_COMMAND = re.compile(r"docker|kubectl|helm|sudo|brew|apt|pip|npm|git |ssh|bal |"
                            r"<[^>]+>|YOUR_|your-|\$\{|rm -rf|https://(?!localhost)", re.I)


def _shell_command(fence: tuple[str, str]) -> str | None:
    lang, code = fence
    lines = [ln.strip() for ln in code.splitlines()
             if ln.strip() and not ln.strip().startswith("#")]
    if lang not in SHELL_LANGS + ("",) or len(lines) != 1:
        return None
    cmd = lines[0].lstrip("$ ").strip()
    if not LOCAL_COMMAND.match(cmd) or UNSAFE_COMMAND.search(cmd) or "`" in cmd:
        return None
    if cmd.startswith("curl") and not re.search(r"localhost|127\.0\.0\.1", cmd):
        return None
    return cmd


def _normalise(text: str, fences: list[tuple[str, str]] | None = None) -> list[str]:
    """The docs' phrasing → the phrasings the parser and doc_to_workflow know.

    Returns zero or more candidate lines. Never invents a value: a field whose
    value is described ("your database username") stays unparsed.
    """
    fm = FENCE_MARK_RE.search(text)
    if fm:
        text = FENCE_MARK_RE.sub("", text).strip()
        cmd = _shell_command(fences[int(fm.group(1))]) if fences else None
        if cmd and re.search(r"\b(run|execute|send|trigger|create|publish|terminal|command)\b",
                             text, re.I):
            return [f"Run the shell command `{cmd}`."]
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text).strip()     # links → text
    t = re.sub(r"\s+\(see [^)]*\)", "", t)
    t = t.replace("\\", "")
    # "`/tmp` (macOS/Linux) or `C:\tmp` (Windows)" — this records on a Mac.
    t = re.sub(r"\s*\((?:macOS(?:/Linux)?|Linux/macOS)\)\s*or\s*`[^`]*`\s*\(Windows\)", "", t)

    sub = t.startswith("  - ")
    if sub:
        t = t[4:].strip()
        m = FIELD_VALUE_RE.match(t)
        if m:
            return [f"Set **{m.group(1)}** to `{m.group(2)}`."]
        return [t]

    if re.match(r"^\*\*[^*]+\*\*\.?$", t):                       # "**Create Integration**."
        return [f"Select {t.rstrip('.')}."]

    # Expanding a tree node is a click on it: "Expand **Connections → client**",
    # "Under **Connections**, expand **client** to view its operations".
    m = re.match(r"^(?:under \*\*([^*]+)\*\*,\s*)?(?:click to )?expand(?: the)? \*\*([^*]+)\*\*", t, re.I)
    if m:
        scope, node = m.group(1), m.group(2)
        parts = [x.strip() for x in re.split(r"\s*(?:→|->|>)\s*", node) if x.strip()]
        if len(parts) > 1:
            scope, node = parts[-2], parts[-1]
        return [f"Select **{node}** under **{scope}**." if scope else f"Select **{node}**."]

    m = CLICK_VERBS.match(t)
    if m:
        t = (m.group("pre") or "") + ("select " if m.group("pre") else "Select ") + t[m.end():]

    m = ENTER_IN_RE.match(t)
    if m:
        return [f"Set **{m.group(2)}** to `{m.group(1)}`."]

    m = SEARCH_TYPE_RE.match(t)
    if m:
        return [f"Search for `{m.group(1)}`."]

    # "Set **Host** to `localhost` and **Port** to `5672` (…)" → two lines.
    if re.match(r"^set\b", t, re.I) and COMPOUND_SET_RE.search(t):
        parts = COMPOUND_SET_RE.split(t)
        out = [parts[0].rstrip(".") + "."]
        for p in parts[1:]:
            p = re.sub(r"\s*\([^)]*\)\s*\.?$", "", p).rstrip(".")
            out.append(f"Set {p}.")
        return out

    t = re.sub(r"\s*\((?:update|change|optional|if )[^)]*\)", "", t)
    return [t]


def _parse(line: str) -> int:
    return len(_parse_instructions(f"1. {line}"))


# An instruction that tells the reader to decide something. It may still
# contain a clickable word ("Fill in the form fields and select Create"), but
# following it to the letter needs values the page never gives.
VAGUE = re.compile(
    r"\b(fill in|fill out|configure the (?:following|fields|settings|required)|"
    r"(?:enter|set|provide|specify) (?:a|an|your|the required|the following|any)\b(?! `)|"
    r"give (?:it|the \w+) a\b|add (?:its|the|your) (?:fields|values|details|logic)|"
    r"write (?:the|your)|implement (?:the|your)|define the (?:input|output|logic)|"
    r"as needed|if needed|your own|as required)", re.I)
ACTION_WORD = re.compile(r"\b(select|click|set|search|add|press)\s+\*\*", re.I)


def _grounded(source: str, line: str, integration: str | None) -> bool:
    """Every target the parser took from `line` is something the doc itself
    marked as a UI label (bold) or a value (code) — not a phrase the rewrite
    wrapped in bold on its own initiative."""
    marked = {m.lower().strip() for m in re.findall(r"\*\*([^*]+)\*\*|`([^`]+)`", source)
              for m in m if m}
    marked |= {part.strip() for m in list(marked) for part in re.split(r"→|->|>", m)}
    if integration:
        marked.add(integration.lower())
    marked.add("skip for now")
    for act in _parse_instructions(f"1. {line}"):
        kind = act["action"]
        want = act.get("target") if kind == "click" else act.get("value") \
            if kind in ("type", "search", "select") else None
        if want and want.lower().strip() not in marked and not (
                kind == "click" and want.lower() in source.lower() and
                re.search(r"\*\*" + re.escape(want), source, re.I)):
            return False
    return True


# Verbs FlowCast has no action for. A clause starting with one is left to a
# person even when the rest of its sentence parses ("select the card, and bind
# each connection parameter to a configurable variable").
NO_ACTION_VERB = re.compile(
    r"^(?:then\s+|and\s+)*(bind|hover|configure|fill|provide|define|write|locate|place|"
    r"switch|update|edit|drag|right-click|copy|paste|replace|upload|enter|type|set|give|"
    r"add (?:its|the|your|a|an) (?!\*\*)|choose (?:a|an|your)|pick (?:a|an|your)|review)\b", re.I)
CLAUSE_SPLIT = re.compile(r";\s*|\.\s+(?=[A-Z*])|,\s*(?:and\s+|then\s+)?(?=(?:then\s+)?[a-z]+\b)|"
                          r"\s+(?:and|then)\s+(?=(?:then\s+)?(?:select|click|bind|hover|set|enter|"
                          r"search|expand|configure|fill|type|choose|open|add)\b)", re.I)


def _uncovered(text: str, integration: str | None) -> list[str]:
    """Clauses of an instruction that ask for something no parsed action does."""
    out = []
    body = re.split(r":\s*(?=-\s|\s*$)", text)[0]          # the list after "…fields:" is detail
    for clause in CLAUSE_SPLIT.split(body):
        c = clause.strip(" .")
        plain = re.sub(r"[*`]", "", c)
        if not plain or not NO_ACTION_VERB.match(plain):
            continue
        cands = _normalise(c)
        if any(_parse(x) or _parse(_dtw_rewrite(x, integration)[0]) for x in cands) \
                and not re.match(r"^(?:then\s+|and\s+)*(bind|hover|configure|fill|provide)\b", plain, re.I):
            continue
        out.append(plain)
    return out


def _clauses(line: str, integration: str | None, source: str) -> list[str]:
    """The line's imperative clauses as parser-legal lines, or [] if it has one."""
    parts = [c.strip(" .") for c in re.split(r",\s*(?:and\s+|then\s+)|\s+(?:and|then)\s+(?=(?:select|click|"
                                             r"search|set|enter|type|press|add)\b)|;\s*", line, flags=re.I)]
    parts = [p for p in parts if p]
    if len(parts) < 2:
        return []
    out = []
    for part in parts:
        cand = next((c for c in _normalise(part[0].upper() + part[1:]) if _parse(c)), None)
        if cand is None:
            rewritten = _dtw_rewrite(part[0].upper() + part[1:], integration)[0]
            cand = rewritten if _parse(rewritten) else None
        if cand is not None and _grounded(source, cand, integration):
            out.append(cand.rstrip(".") + ".")
    return out


def convert_line(text: str, integration: str | None,
                 fences: list[tuple[str, str]] | None = None) -> Line:
    text = text if fences is not None else FENCE_MARK_RE.sub("", text)
    candidates = _normalise(text, fences)
    text = FENCE_MARK_RE.sub("", text).strip()
    plain = re.sub(r"[*`]", "", text).strip().lstrip("- ")
    if INFORMATIONAL.match(plain) and not IMPERATIVE.match(plain) \
            and not ACTION_WORD.search(text):
        return Line(text, [], 0, "info")
    out: list[str] = []
    total = 0
    for cand in candidates:
        n = _parse(cand)
        line = cand
        if n == 0:
            rewritten, _note = _dtw_rewrite(cand, integration)
            if _parse(rewritten):
                line, n = rewritten, _parse(rewritten)
        if n and (line.startswith("Run the shell command") or _grounded(text, line, integration)):
            # The parser takes the first rule that matches a line, so a compound
            # instruction can lose a clause: "Search for `printInfo` and select
            # **printInfo**" parses to the click alone, and the search is never
            # typed. When its clauses, parsed one by one, do more than the whole
            # line did, use the clauses.
            split = _clauses(cand, integration, text)
            if split and sum(_parse(c) for c in split) > n:
                out += split
                total += sum(_parse(c) for c in split)
                continue
            out.append(line)
            total += n
    if total and VAGUE.search(plain) and not any(re.match(r"Set \*\*", w) for w in out):
        return Line(text, out, total, "mixed", manual=plain)
    if total and not any(w.startswith("Run the shell command") for w in out):
        left = _uncovered(text, integration)
        if left:
            return Line(text, out, total, "mixed", manual="; ".join(left))
    if total:
        return Line(text, out, total, "action")
    if INFORMATIONAL.match(plain) and not IMPERATIVE.match(plain):
        return Line(text, [], 0, "info")
    return Line(text, [], 0, "unparsed")


