def _inputs(text: str) -> list[dict]:
    """Configurables a page asks values for, from the bullet list under its
    "Set a value for each configurable" line (or, failing that, under the
    "bind each field to a configurable" line)."""
    lines = text.splitlines()
    values: list[dict] = []
    binds: list[dict] = []
    for i, ln in enumerate(lines):
        if not re.search(r"configurable", ln, re.I) or CONFIG_BULLET.match(ln):
            continue
        target = values if VALUES_LINE.search(re.sub(r"[*`]", "", ln)) else binds
        for nxt in lines[i + 1:i + 40]:
            if not nxt.strip() or re.match(r"^\s{3,}\S", nxt) and not CONFIG_BULLET.match(nxt):
                continue
            m = CONFIG_BULLET.match(nxt)
            if not m:
                break
            name, rest = m.group(1), m.group(2)
            alias = re.search(r"`(\w+)` of type", rest)       # bind lists name the variable
            target.append(_input(alias.group(1) if alias else name, rest))
    chosen = values or binds
    seen, out = set(), []
    for inp in chosen:
        if inp["name"] not in seen:
            seen.add(inp["name"])
            out.append(inp)
    return out


def _recipes_for(requires: list[str]) -> list[str]:
    """One prerequisite recipe per requirement — the service it names first
    ("MySQL, PostgreSQL, MSSQL, or similar" is a MySQL page)."""
    ids: list[str] = []
    for item in requires:
        hits = [(m.start(), r["id"]) for r in prereqs.recipes()
                for m in [re.search(r["match"], item, re.I)] if m]
        if hits:
            rid = min(hits)[1]
            if rid not in ids:
                ids.append(rid)
    return ids


# A requirement the person running FlowCast satisfies by entering values:
# they have the account, the server, the key — FlowCast just needs to be told.
KEYABLE = re.compile(r"key|token|secret|credential|password|username|user id|connection details|"
                     r"account|subscription|tenant|client id|app registration|access to|url|endpoint|"
                     r"host|organi[sz]ation|workspace|instance|server|project id|region", re.I)


def _trigger(text: str, recipe_ids: list[str], names: dict[str, str]) -> str | None:
    """A doc line that sends the test event by hand → the recipe's command."""
    plain = re.sub(r"[*`]", "", text)
    for rid in recipe_ids:
        trig = prereqs.by_id(rid).get("trigger")
        if not trig or not re.search(trig["when"], plain, re.I):
            continue
        vals = {"queue": names.get("queue", "flowcast"), "topic": names.get("topic", "flowcast"),
                "payload": "hello-from-flowcast"}
        cmd, why = trig["command"].format(**vals), trig["why"].format(**vals)
        return f"Run the shell command `{cmd}` to {why}."
    return None


EPILOGUE = re.compile(r"^(?:deploy\b|deploy(?:ing)? to|next steps?|what'?s next|clean ?up|"
                      r"tear ?down|further reading)", re.I)


# ── page assembly ─────────────────────────────────────────────────────────────

def _url(rel: Path, fm: dict) -> str:
    if fm.get("slug"):
        return DOCS_SITE + "/" + fm["slug"].strip("/")
    parts = list(rel.with_suffix("").parts)
    if parts and parts[-1] == "index":
        parts = parts[:-1]
    return DOCS_SITE + "/" + "/".join(parts)


GENERIC_STEMS = {"example", "overview", "setup-guide", "actions", "action-reference",
                 "triggers", "trigger-reference", "connector-overview", "index"}


def _slug(rel: Path) -> str:
    parts = [p for p in rel.with_suffix("").parts]
    keep = parts[-1:]
    i = len(parts) - 1
    while keep[0] in GENERIC_STEMS and i > 0 or (len(keep) == 1 and re.match(r"^\d", keep[0])):
        i -= 1
        keep.insert(0, parts[i])
    return re.sub(r"[^a-z0-9]+", "-", "-".join(keep).lower()).strip("-")


def _area(rel: Path) -> str:
    p = rel.parts
    if p[0] == "connectors" and len(p) > 2 and p[1] == "catalog":
        return f"Connectors · {p[2].replace('-', ' ').title()}"
    names = {"get-started": "Get started", "develop": "Develop", "genai": "GenAI",
             "guides": "Guides", "connectors": "Connectors", "deploy": "Deploy",
             "deploy-operate": "Deploy & operate", "manage": "Manage",
             "reference": "Reference"}
    return names.get(p[0], p[0].title())


def analyse(path: Path, docs_root: Path) -> Page:
    rel = path.relative_to(docs_root)
    raw = path.read_text(errors="replace")
    fm, body = _frontmatter(raw)
    h1 = re.search(r"^#\s+(.+)$", body, re.M)
    title = fm.get("title") or (h1.group(1).strip() if h1 else rel.stem.replace("-", " ").title())
    page = Page(path=str(rel.with_suffix("")), url=_url(rel, fm), title=title,
                description=fm.get("description", ""), section="/".join(rel.parts[:2]),
                area=_area(rel), slug=_slug(rel))
    m = META_RE.search(body)
    if m:
        page.time, page.build = m.group("time").strip(), re.sub(r"[`*]", "", m.group("build")).strip()

    text, fences, admonitions, prereq = _clean(body)
    page.requires, page.setup_commands = _requirements(prereq, fences)
    sections = _sections(text)

    step_secs = [(lvl, STEP_HEADING_RE.match(h), ls) for lvl, h, ls in sections
                 if STEP_HEADING_RE.match(h)]
    raw_steps: list[tuple[str, list[str]]] = []
    if step_secs:
        for _lvl, m, ls in step_secs:
            items = _items(ls) or _paragraph_items(ls)
            if not items:
                # A step whose instruction is prose the rules above do not pick
                # up ("Bind every required connection field to a configurable
                # variable.") is still a step. Dropping it would make the page
                # look followable while the recording skips the hard part.
                prose = " ".join(ln.strip() for ln in ls if ln.strip()
                                 and not FENCE_MARK_RE.search(ln) and not ln.strip().startswith("|"))
                first = re.split(r"(?<=[.!:])\s+", prose)[0] if prose else ""
                if first and not INFORMATIONAL.match(re.sub(r"[*`]", "", first)):
                    items = [first]
            raw_steps.append((m.group(2).strip() or f"Step {m.group(1)}", items))
    else:
        # No "Step N" headings: a section with a numbered list of at least two
        # imperative lines is a procedure step of its own.
        for _lvl, h, ls in sections:
            items = _items(ls)
            if sum(1 for i in items if IMPERATIVE.match(re.sub(r"[*`]", "", i))) >= 2:
                raw_steps.append((h or page.title, items))

    integration = None
    names: dict[str, str] = {}
    for _t, items in raw_steps:
        for it in items:
            mm = re.search(r"Set\s+\*{0,2}Integration Name\*{0,2}\s+to\s+`([^`]+)`", it, re.I)
            if mm:
                integration = mm.group(1)
            mm = re.search(r"Set\s+\*{0,2}Project Name\*{0,2}\s+to\s+`([^`]+)`", it, re.I)
            if mm:
                page.project = mm.group(1)
            for key, rx in (("queue", r"Queue(?: Name)?"), ("topic", r"Topics?(?: Name)?")):
                mm = re.search(rf"\*\*{rx}\*\*\s+to\s+`([^`]+)`", it, re.I)
                if mm:
                    names[key] = mm.group(1)
    page.project = page.project or page.slug[:40]
    page.recipes = _recipes_for(page.requires)
    page.inputs = _inputs(text)
    page.bindings = _bindings(text, page.inputs)
    page.service = _service(rel)
    for inp in page.inputs:
        inp["auto"] = prereqs.value_for(inp["name"], page.recipes) if page.recipes else None

    triggered = False
    for n, (title_, items) in enumerate(raw_steps, 1):
        step = Step(n, re.sub(r"[`*]", "", title_))
        consume = False             # sub-bullets of a line replaced as a whole
        for it in items:
            if consume and it.startswith("  - "):
                step.lines.append(Line(FENCE_MARK_RE.sub("", it), [], 0, "info"))
                continue
            consume = False
            plain = re.sub(r"[*`]", "", it)
            if page.inputs and VALUES_LINE.search(plain):
                # Values go to Config.toml off camera; nothing secret is typed.
                expect = ",".join(i["name"] for i in page.inputs)
                cmd = (f".venv/bin/python tools/write_config.py --project {page.project} "
                       f"--expect {expect}")
                step.lines.append(Line(it, [f"Run the shell command `{cmd}` to set the "
                                            f"configurable values."], 1, "action"))
                consume = True
                continue
            line = convert_line(it, integration, fences)
            if line.kind == "unparsed" and page.recipes:
                trig = _trigger(it, page.recipes, names)
                if trig:
                    line = Line(line.source, [trig], 1, "action")
                    triggered = consume = True
            step.lines.append(line)
        page.steps.append(step)

    # A step with nothing to do is not part of the recording, and neither is the
    # optional epilogue quick starts end with ("Deploy to WSO2 Cloud" — after
    # the walkthrough, and it needs a cloud account). It is noted on the card.
    epilogue = [s for s in page.steps if EPILOGUE.search(s.title)]
    if epilogue and len(epilogue) < len(page.steps):
        page.notes_extra = [f"optional step not recorded: {s.title}" for s in epilogue]
        page.steps = [s for s in page.steps if s not in epilogue]
    page.steps = [s for s in page.steps if any(ln.kind != "info" for ln in s.lines)]
    for n, s in enumerate(page.steps, 1):
        s.n = n

    handled = set(page.setup_commands) | {
        m.group(1) for s in page.steps for ln in s.lines for w in ln.workflow
        for m in [re.match(r"Run the shell command `(.+)`", w)] if m}
    open_fences = [f for f in fences if _shell_command(f) not in handled
                   and (f[0] in SHELL_LANGS + ("cmd", "powershell"))]
    # Scan what the reader is told to DO (and the notes beside it), not the
    # intro prose: "files appearing in a folder or FTP server" describes the
    # feature, it does not ask for a server.
    instructions = "\n".join(it for _t, items in raw_steps for it in items)
    hard, soft = _blockers(FENCE_MARK_RE.sub("", instructions) + "\n" + "\n".join(admonitions)
                           + "\n" + prereq, open_fences, page.requires)
    for item in page.requires:
        started = any(re.search(prereqs.by_id(r)["match"], item, re.I) for r in page.recipes)
        if not started and not (page.inputs and KEYABLE.search(item)):
            page.manual_requires.append(item)
    covered = set()
    if page.recipes:
        covered.add("service")
    if not page.manual_requires:
        covered.add("prerequisite")
    if page.inputs:
        covered |= {"credentials", "account"}   # you have them; FlowCast is told
    if triggered:
        covered.add("external-ui")
    page.blockers = [b for b in hard if b not in covered]
    page.notes = soft

    lines = [ln for s in page.steps for ln in s.lines]
    acts = [ln for ln in lines if ln.kind != "info"]
    parsed = [ln for ln in acts if ln.kind == "action"]
    page.action_count = sum(ln.actions for ln in acts if ln.kind in ("action", "mixed"))
    page.coverage = round(len(parsed) / len(acts), 3) if acts else 0.0
    page.unparsed = [ln.manual or ln.source for ln in acts if ln.kind in ("unparsed", "mixed")][:12]

    if len(acts) < 3:
        page.verdict = "none"            # fewer than three things to do: not a walkthrough
    elif page.action_count < 3:
        page.verdict = "partial"
    elif page.coverage < 1.0:
        page.verdict = "partial"
    elif page.blockers:
        page.verdict = "setup"
    elif any(i["auto"] is None for i in page.inputs):
        page.verdict = "keys"
    elif page.recipes or page.inputs:
        page.verdict = "auto"
    elif page.coverage == 1.0:
        page.verdict = "ready"
    else:
        page.verdict = "partial"
    if page.steps:
        first = " ".join(w for ln in page.steps[0].lines for w in ln.workflow)
        page.starts_in_project = not re.search(
            r"Open WSO2 Integrator|Create New Integration|Create Integration", first, re.I)
    page.verified = VERIFIED_WORKFLOWS.get(page.path)
    return page


# ── workflow file ─────────────────────────────────────────────────────────────

def workflow_markdown(page: Page) -> str:
    """The page as a FlowCast workflow, in the shape of the recordings that
    already work (see workflows/build-integration-api.md)."""
    integration = None
    for s in page.steps:
        for ln in s.lines:
            for w in ln.workflow:
                m = re.match(r"Set \*\*Integration Name\*\* to `([^`]+)`", w)
                if m:
                    integration = m.group(1)
    out: list[str] = []
    offset = 0
    if page.starts_in_project:
        # The docs say "follow Create a New Integration first, then return
        # here" — so that is what the recording does.
        integration = integration or re.sub(r"[^A-Za-z0-9]", "", page.title.title())[:28] or "Demo"
        out += ["## Step 1: Create the integration\n",
                "1. Open WSO2 Integrator.",
                "2. Select **Skip for now**.",
                "3. Select **Create New Integration**.",
                f"4. Set **Integration Name** to `{integration}`.",
                f"5. Set **Project Name** to `{page.slug[:40]}`.",
                "6. Select **Create Integration**.",
                f"7. Select **{integration}**.", ""]
        out[1:1] = [f"{i}. Run the shell command `{c}` to prepare the prerequisites."
                    for i, c in enumerate(page.setup_commands, 1)]
        if page.setup_commands:   # renumber
            nums = iter(range(1, 100))
            out = [re.sub(r"^\d+\.", lambda _m: f"{next(nums)}.", ln) if re.match(r"^\d+\.", ln)
                   else ln for ln in out]
        offset = 1
    opened_handler: str | None = None
    for s in page.steps:
        out.append(f"## Step {s.n + offset}: {s.title}\n")
        body: list[str] = []
        # A handler added from "+ Add Handler" without a Save is created but not
        # opened; a step that then starts with "Select +" (in its flow) needs it
        # open first. Seen on the File-Driven quick start (Oct 3 run) and done
        # by hand in workflows/quick-start-file.md ("Select onModify again").
        first = next((w for ln in s.lines for w in ln.workflow), "")
        if opened_handler and re.match(r"^Select \*\*\+\*\*", first):
            body.append(f"Select **{opened_handler}**.")
        acts = [w for ln in s.lines for w in ln.workflow]
        opened_handler = None
        for a, b in zip(acts, acts[1:]):
            if re.match(r"^(?:.*\b)?select \*\*\+ Add Handler\*\*", a, re.I):
                m = re.match(r"^Select \*\*(on\w+)\*\*\.?$", b)
                if m and not any("**Save**" in x for x in acts[acts.index(b):]):
                    opened_handler = m.group(1)
        if s.n == 1 and not offset:
            body += [f"Run the shell command `{c}` to prepare the prerequisites."
                     for c in page.setup_commands]
        for ln in s.lines:
            if ln.kind == "info":
                note = re.sub(r"\s+", " ", ln.source).strip().lstrip("- ").rstrip(".") + "."
                # Kept for whoever reads the workflow — but a note that the
                # parser could still read as an action ("…and select **Publish
                # message**", absorbed by a trigger) must be invisible to it.
                if _parse(note):
                    note = f"<!-- note: {note.replace('<', '‹').replace('>', '›')} -->"
                body.append(note)
                continue
            if ln.kind == "unparsed":
                # A checkpoint the parser ignores (HTML is stripped) and
                # tools/autopilot.py stops at, handing you the doc's own words.
                text = re.sub(r"\s+", " ", re.sub(r"[*`]", "", ln.source)).strip().lstrip("- ")
                body.append(f"<!-- manual: {text.replace('<', '‹').replace('>', '›')} -->")
                continue
            if ln.kind == "mixed":
                body += [re.sub(r"\s+", " ", w).strip() for w in ln.workflow]
                text = re.sub(r"\s+", " ", ln.manual).strip()
                body.append(f"<!-- manual: {text.replace('<', '‹').replace('>', '›')} -->")
                continue
            for w in ln.workflow:
                w = re.sub(r"\s+", " ", w).strip()
                if re.match(r"^Select \*\*Run\*\*\.?$", w):
                    w = "Select **Run** in the toolbar."
                # File Integration is the last section of the Artifacts page and
                # starts below the fold on a laptop screen. (The parser's
                # "under" rule would swallow a "Scroll down and …" prefix, so the
                # scope is dropped to keep the scroll.)
                w = re.sub(r"^Select (\*\*[^*]+\*\*) under \*\*File Integration\*\*\.?$",
                           r"Scroll down and select \1.", w)
                body.append(w)
                if re.match(r"^Open WSO2 Integrator", w, re.I):
                    body.append("Select **Skip for now**.")
        # Timing the recorder needs and the docs leave implicit (the same dwell
        # the hand-tuned workflows/build-event-integration.md uses): give a
        # started integration time to come up before anything is sent to it,
        # and keep the result on screen after the step's last action.
        runs = [i for i, b in enumerate(body) if re.search(r"\*\*(Run|Execute|Send|Test)\*\*", b)]
        if runs and not any(b.startswith("Wait ") for b in body):
            acts = [i for i, b in enumerate(body) if _parse(b)]
            last = max(acts)
            after = [i for i in acts if i > runs[0]]
            if after and re.search(r"\*\*Run\*\*", body[runs[0]]) and \
                    body[after[0]].startswith("Run the shell command"):
                body.insert(runs[0] + 1, "Wait 10 seconds.")
                last += 1
            body.insert(last + 1, "Wait 8 seconds.")
        out += [f"{i}. {b}" for i, b in enumerate(body, 1)]
        out.append("")
    if integration:
        out = [ln.replace("Select **your integration**", f"Select **{integration}**") for ln in out]
    return "\n".join(out).rstrip() + "\n"


# ── whole catalog ─────────────────────────────────────────────────────────────

def build(docs_root: Path, write_workflows: bool = True) -> dict:
    pages: list[Page] = []
    for p in sorted(docs_root.rglob("*")):
        if p.suffix not in (".md", ".mdx") or "/_" in str(p):
            continue
        pages.append(analyse(p, docs_root))

    seen: dict[str, int] = {}
    for pg in pages:                                   # unique slugs
        if pg.slug in seen:
            seen[pg.slug] += 1
            pg.slug = f"{pg.slug}-{seen[pg.slug]}"
        else:
            seen[pg.slug] = 1

    if write_workflows:
        WORKFLOW_DIR.mkdir(parents=True, exist_ok=True)
        for old in WORKFLOW_DIR.glob("*.md"):
            old.unlink()
        for pg in pages:
            if pg.verdict != "none":
                f = WORKFLOW_DIR / f"{pg.slug}.md"
                f.write_text(f"{GENERATED_MARK} {pg.url} -->\n\n" + workflow_markdown(pg))
                (WORKFLOW_DIR / f"{pg.slug}.meta.json").write_text(json.dumps({
                    "title": pg.title, "time": pg.time, "build": pg.build,
                    "links": [["Documentation", pg.url]], "slug": pg.slug}, indent=2))
                pg.workflow_file = str(f.relative_to(ROOT))

    counts = {v: sum(1 for p in pages if p.verdict == v) for v in VERDICTS}
    by_area: dict[str, dict[str, int]] = {}
    for p in pages:
        a = by_area.setdefault(p.area.split(" · ")[0], {v: 0 for v in VERDICTS})
        a[p.verdict] += 1
    blocker_counts: dict[str, int] = {}
    for p in pages:
        if p.verdict == "setup":
            for b in p.blockers:
                blocker_counts[b] = blocker_counts.get(b, 0) + 1
    return {
        "version": 1,
        "source": DOCS_REPO,
        "site": DOCS_SITE,
        "commit": source_commit(),
        "summary": {"total": len(pages), "walkthroughs": len(pages) - counts["none"],
                    **counts, "verified": sum(1 for p in pages if p.verified),
                    "by_area": by_area, "setup_blockers": blocker_counts},
        "pages": [asdict(p) for p in pages],
    }


def load() -> dict:
    return json.loads(CATALOG.read_text()) if CATALOG.exists() else {}
