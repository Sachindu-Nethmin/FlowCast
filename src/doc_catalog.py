"""Which WSO2 Integrator docs pages can FlowCast follow, start to finish?

`tools/doc_to_workflow.py` converts ONE pasted page. This module reads the
whole docs source (https://github.com/wso2/docs-integrator, the Markdown the
site at https://wso2.com/integration-platform/docs/ is built from) and, for
every page, answers the question the recorder actually cares about: if FlowCast
were handed this page, would every instruction turn into an action it can run?

The answer is decided by the real parser, not by guessing. Each numbered
instruction is normalised (the docs say "click", the parser speaks "Select"),
passed through `doc_to_workflow.rewrite`, then through
`parser._parse_instructions`. A line either produces actions, is purely
informational ("Confirm the response shows 200 OK"), or is UNPARSED — and one
unparsed line means a person has to step in.

Verdicts, strictest first:

    ready    every line parses, nothing outside WSO2 Integrator is needed.
             This is the "100% followable" set.
    auto     every line parses once FlowCast starts the page's prerequisites
             itself (a broker or database container, kb/prereq_recipes.json)
             and sends its test event. Hands-free, with Docker.
    keys     every line parses, but the page's configurables need values only
             you have (an API key, a tenant URL). Enter them once in FlowCast
             Studio; they are written to Config.toml, never typed on camera.
    setup    every line parses, but the page needs something FlowCast cannot
             create or be given: an account to sign up for, a cloud console.
    partial  a walkthrough, but some lines have no concrete value or no rule
             ("configure the following fields") — needs a person.
    none     not a walkthrough: concepts, reference, overviews.

The parse is static. A `ready` page has a workflow FlowCast can execute line
for line; whether every click lands is only proven by recording it, which is
what the `verified` flag records.
"""
